"""Read-only prompt library (提示词库) served to the Assets page.

The data is generated by ``scripts/import_prompts.py`` into
``studio/config/prompt_library/`` and shipped with the image; this module only
reads it. Every entry carries its own source, license and attribution, which
the UI shows next to the prompt. Browsing is public (GET under
``/api/platform/prompts`` is in the auth allowlist); saving an entry into the
user's own prompts goes through the existing ``POST /api/platform/prompts``,
which requires a login.
"""

from __future__ import annotations

import json
import threading
from pathlib import Path
from typing import Any

from fastapi import APIRouter, HTTPException, Query

LIBRARY_DIRS = (
    Path(__file__).resolve().parents[1] / "config" / "prompt_library",
    Path("/app/studio/config/prompt_library"),
)
CREDITS_URL = "https://github.com/charliewwdev/OpenMontage/blob/main/prompts/library/ATTRIBUTION.md"
MAX_LIMIT = 100
DEFAULT_LIMIT = 24
BASIC_EXAMPLE_TAG = "基础例句"

_lock = threading.Lock()
_cache: dict[str, Any] | None = None


def library_dir() -> Path | None:
    for d in LIBRARY_DIRS:
        if (d / "prompts.json").is_file():
            return d
    return None


def _read_json(path: Path, default: Any) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return default


def _search_blob(item: dict[str, Any]) -> str:
    title = item.get("title") or {}
    parts = [
        item.get("id"),
        title.get("zh"),
        title.get("en"),
        item.get("prompt_zh"),
        item.get("prompt_en"),
        item.get("subcategory"),
        " ".join(item.get("tags") or []),
    ]
    return " ".join(str(p) for p in parts if p).lower()


def _decorate(item: dict[str, Any]) -> dict[str, Any]:
    out = dict(item)
    tags = list(item.get("tags") or [])
    out["basicExample"] = BASIC_EXAMPLE_TAG in tags
    out["aiTranslated"] = item.get("translated") == "machine"
    out["original"] = (item.get("source") or {}).get("name") == "OpenMontage"
    return out


def load(force: bool = False) -> dict[str, Any]:
    """Load and index the library once per process (it is static data)."""
    global _cache
    with _lock:
        if _cache is not None and not force:
            return _cache
        d = library_dir()
        items: list[dict[str, Any]] = []
        categories: list[dict[str, Any]] = []
        stats: dict[str, Any] = {}
        if d is not None:
            raw = _read_json(d / "prompts.json", [])
            items = [_decorate(x) for x in raw if isinstance(x, dict) and x.get("id")]
            categories = _read_json(d / "categories.json", [])
            stats = _read_json(d / "stats.json", {})
        _cache = {
            "items": items,
            "byId": {x["id"]: x for x in items},
            "blobs": {x["id"]: _search_blob(x) for x in items},
            "categories": categories if isinstance(categories, list) else [],
            "stats": stats if isinstance(stats, dict) else {},
        }
        return _cache


def _norm(value: str | None) -> str:
    v = (value or "").strip()
    return "" if v.lower() in ("", "all", "*", "全部") else v


def query(
    *,
    q: str = "",
    category: str = "",
    subcategory: str = "",
    model: str = "",
    stage: str = "",
    tags: list[str] | None = None,
    source: str = "",
    offset: int = 0,
    limit: int = DEFAULT_LIMIT,
) -> dict[str, Any]:
    lib = load()
    items: list[dict[str, Any]] = lib["items"]
    category, subcategory, model, stage = _norm(category), _norm(subcategory), _norm(model), _norm(stage)
    source = _norm(source)
    want_tags = [t.strip() for t in (tags or []) if t and t.strip()]
    terms = [t for t in (q or "").lower().split() if t]

    def keep(x: dict[str, Any]) -> bool:
        if category and x.get("category") != category:
            return False
        if subcategory and x.get("subcategory") != subcategory:
            return False
        if model and str(x.get("model") or "").lower() != model.lower():
            return False
        if stage and x.get("stage") != stage:
            return False
        if source == "original" and not x.get("original"):
            return False
        if source == "third-party" and x.get("original"):
            return False
        if want_tags and not all(t in (x.get("tags") or []) for t in want_tags):
            return False
        if terms:
            blob = lib["blobs"].get(x["id"], "")
            if not all(t in blob for t in terms):
                return False
        return True

    matched = [x for x in items if keep(x)]
    total = len(matched)
    offset = max(0, int(offset or 0))
    limit = max(1, min(int(limit or DEFAULT_LIMIT), MAX_LIMIT))
    page = matched[offset : offset + limit]
    next_offset = offset + len(page)
    return {
        "items": page,
        "total": total,
        "offset": offset,
        "limit": limit,
        "hasMore": next_offset < total,
        "nextOffset": next_offset if next_offset < total else None,
    }


def facets() -> dict[str, Any]:
    lib = load()
    items = lib["items"]
    models = sorted({str(x.get("model")) for x in items if x.get("model")}, key=lambda m: (m == "generic", m))
    stages = sorted({str(x.get("stage")) for x in items if x.get("stage")})
    return {
        "categories": lib["categories"],
        "models": models,
        "stages": stages,
        "total": len(items),
        "stats": lib["stats"],
        "creditsUrl": CREDITS_URL,
    }


router = APIRouter()


@router.get("/api/platform/prompts/library")
def prompt_library_list(
    q: str = Query(""),
    category: str = Query(""),
    subcategory: str = Query(""),
    model: str = Query(""),
    stage: str = Query(""),
    tag: list[str] = Query(default=[]),
    source: str = Query(""),
    offset: int = Query(0, ge=0),
    limit: int = Query(DEFAULT_LIMIT, ge=1, le=MAX_LIMIT),
) -> dict[str, Any]:
    return query(
        q=q,
        category=category,
        subcategory=subcategory,
        model=model,
        stage=stage,
        tags=tag,
        source=source,
        offset=offset,
        limit=limit,
    )


@router.get("/api/platform/prompts/library/meta")
def prompt_library_meta() -> dict[str, Any]:
    return facets()


@router.get("/api/platform/prompts/library/items/{entry_id}")
def prompt_library_item(entry_id: str) -> dict[str, Any]:
    item = load()["byId"].get(entry_id)
    if item is None:
        raise HTTPException(status_code=404, detail="prompt not found")
    return {"item": item}
